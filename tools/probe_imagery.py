#!/usr/bin/env python3
"""Find how deep the satellite imagery really goes at each monument.

    python3 -I tools/probe_imagery.py      # writes content/imagery_zoom.json

Esri World Imagery does not return an error where it has no imagery at a zoom level: it
returns a grey "Map data not yet available" picture. The game cannot tell that picture from
a real one, so it must never ask for those tiles. This tool checks, for every ARGUS sensor
position of every monument, the deepest zoom that still returns real imagery, and stores the
smallest of them per monument. The game then stretches that last real level instead of asking
for deeper tiles (Leaflet maxNativeZoom).

Which layers are probed: raster layers in content/map.json with "probe_zoom": true.
The "not available" picture is recognised by comparing it with the tile for a point in the
middle of the Atlantic at the deepest zoom, which never has imagery.
Run it again when a monument gets new sensor positions. Standard library only; needs internet.
"""
from __future__ import annotations

import datetime as dt
import json
import math
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
GAME_DATA = ROOT / "web" / "public" / "data" / "game_data.json"
MAP_CONTENT = ROOT / "content" / "map.json"
OUT = ROOT / "content" / "imagery_zoom.json"
USER_AGENT = "guardian-for-a-day/0.1 (ARGUS Open Innovation Challenge educational game)"
DEEPEST, SHALLOWEST = 21, 14  # the game's map allows zoom 21
NOWHERE = (0.0, -30.0)  # mid-Atlantic: never has imagery at deep zoom


def tile_xy(lat: float, lon: float, z: int) -> Tuple[int, int]:
    n = 2 ** z
    x = int((lon + 180.0) / 360.0 * n)
    y = int((1.0 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2.0 * n)
    return x, y


class Prober:
    def __init__(self, url: str):
        self.url = url
        self.cache: Dict[Tuple[int, int, int], bytes] = {}
        self.placeholder = self.fetch(DEEPEST, *tile_xy(NOWHERE[0], NOWHERE[1], DEEPEST))
        if not self.placeholder:
            raise RuntimeError("could not fetch the reference 'not available' tile")

    def fetch(self, z: int, x: int, y: int) -> bytes:
        key = (z, x, y)
        if key not in self.cache:
            request = urllib.request.Request(self.url.format(z=z, x=x, y=y), headers={"User-Agent": USER_AGENT})
            try:
                with urllib.request.urlopen(request, timeout=30) as response:
                    self.cache[key] = response.read()
            except urllib.error.HTTPError:
                self.cache[key] = b""
        return self.cache[key]

    def real(self, z: int, lat: float, lon: float) -> bool:
        body = self.fetch(z, *tile_xy(lat, lon, z))
        return bool(body) and body != self.placeholder

    def deepest_real(self, lat: float, lon: float) -> Optional[int]:
        for z in range(DEEPEST, SHALLOWEST - 1, -1):
            if self.real(z, lat, lon):
                return z
        return None


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    game = json.loads(GAME_DATA.read_text(encoding="utf-8"))
    layers = [l for l in json.loads(MAP_CONTENT.read_text(encoding="utf-8"))["layers"] if l.get("probe_zoom")]
    result: Dict[str, Dict[str, int]] = {}
    for layer in layers:
        prober = Prober(layer["url"])
        result[layer["id"]] = {}
        for mon in game["monuments"]:
            points: List[Tuple[float, float]] = [(p["lat"], p["lon"]) for p in (mon.get("installed") or {}).get("points", [])]
            if not points and mon.get("map"):
                points = [tuple(mon["map"]["center"])]
            depths = [prober.deepest_real(lat, lon) for lat, lon in points]
            known = [d for d in depths if d is not None]
            if not known:
                print(f"probe_imagery: {layer['id']} {mon['pilot_key']}: no real imagery found", file=sys.stderr)
                continue
            result[layer["id"]][mon["pilot_key"]] = min(known)
            print(f"probe_imagery: {layer['id']:9s} {mon['pilot_key']:13s} real imagery to zoom {min(known)} "
                  f"(points: {', '.join(str(d) for d in depths)})")
    OUT.write_text(json.dumps({
        "_about": "GENERATED by tools/probe_imagery.py; do not edit. Deepest zoom with real imagery at every "
                  "ARGUS sensor position, per raster layer and monument. Above it the provider returns a "
                  "'Map data not yet available' picture, so the game stretches this level instead.",
        "checked": dt.date.today().isoformat(),
        "layers": result,
    }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"probe_imagery: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
